CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY,name TEXT UNIQUE NOT NULL,salt TEXT NOT NULL,hash TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(sid TEXT PRIMARY KEY,uid TEXT NOT NULL,exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS lib(uid TEXT PRIMARY KEY,data TEXT NOT NULL,updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rooms(id TEXT PRIMARY KEY,host TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS entries(id TEXT PRIMARY KEY,uid TEXT NOT NULL,kind TEXT NOT NULL,artist TEXT,day TEXT,data TEXT NOT NULL,created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS e_uid ON entries(uid,kind);
CREATE INDEX IF NOT EXISTS e_gig ON entries(kind,artist,day);
CREATE TABLE IF NOT EXISTS follows(follower TEXT NOT NULL,followee TEXT NOT NULL,PRIMARY KEY(follower,followee));
CREATE TABLE IF NOT EXISTS resolved(k TEXT PRIMARY KEY,ref TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS profiles(uid TEXT PRIMARY KEY,bio TEXT,avatar TEXT,banner TEXT,updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS usage(uid TEXT NOT NULL,day TEXT NOT NULL,kind TEXT NOT NULL,n INTEGER NOT NULL,PRIMARY KEY(uid,day,kind));
